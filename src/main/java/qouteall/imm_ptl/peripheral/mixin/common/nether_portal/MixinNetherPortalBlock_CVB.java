package qouteall.imm_ptl.peripheral.mixin.common.nether_portal;

import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.level.block.NetherPortalBlock;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(NetherPortalBlock.class)
public class MixinNetherPortalBlock_CVB {
    // Vanilla makes survival players stand in a nether portal for
    // RULE_PLAYERS_NETHER_PORTAL_DEFAULT_DELAY (80 ticks) before transferring them, and only
    // creative/spectator players (Abilities.invulnerable) use the 1 tick creative delay.
    // Immersive Portals normally never lets this block exist, but any portal that predates the
    // mod, was lit while netherPortalMode was vanilla, or was generated by PortalForcer still
    // goes through this timer. Give every player the instant transition.
    @Inject(method = "getPortalTransitionTime", at = @At("HEAD"), cancellable = true)
    private void ipMakeTransitionInstant(
        ServerLevel level,
        Entity entity,
        CallbackInfoReturnable<Integer> cir
    ) {
        cir.setReturnValue(1);
    }
}
